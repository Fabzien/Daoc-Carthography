// Coordinates are CRS.Simple map-space values, not geographic ones.
export type LatLng = [number, number]

export type NpcKind =
  | 'merchant'
  | 'trainer'
  | 'healer'
  | 'stable'
  | 'boat'
  | 'teleporter'
  | 'guard'
  | 'crafting'
  | 'vault'
  | 'other'

export interface Zone {
  name: string
  bounds: [LatLng, LatLng]
}

export interface Npc {
  name: string
  title: string
  kind: NpcKind
  pos: LatLng
}

export interface Route {
  name: string
  kind: 'horse' | 'boat'
  path: LatLng[]
}

export interface Entrance {
  name: string
  pos: LatLng
  // The map it leads to (a RegionName), and the arrival point there when that map has DOL data.
  target?: { map: string; pos?: LatLng }
}

// A DOL zone in game units, to turn game coordinates into zone-relative /loc ones.
export interface GameZone {
  name: string
  origin: [number, number]
  size: [number, number]
  // For the zone of a region drawn inside the map (a capital): the map square
  // it's drawn in and its own calibration there. Without it, the map's own.
  area?: { bounds: [LatLng, LatLng]; scale: number; offset: [number, number] }
}

// Notable mobs: 1 = named boss (unique, hostile, level 65+), 2 = epic encounter
// (hand-kept list of raid encounters). Absent for ordinary mobs.
export type MobTier = 1 | 2

// Content of public/data/<region>.json, generated by scripts/import-dol.ts.
export interface RegionData {
  source: string
  zones: Zone[]
  // Tuples rather than objects: there are up to ~16k mobs per region.
  mobs: [name: string, level: string, lat: number, lng: number, tier?: MobTier][]
  npcs: Npc[]
  routes: Route[]
  entrances: Entrance[]
  bindPoints: LatLng[]
  // Every zone of the region, drawn or not, in game units.
  gameZones: GameZone[]
}
